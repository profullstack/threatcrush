#!/usr/bin/env node
// Rasterize Natural Earth land (world-atlas land-50m, public domain) into the
// equirectangular bitmask in src/land.ts. Every surface draws its map from this
// one mask, so they all show the same world.
//
//   node packages/attack-map/scripts/build-land.mjs /path/to/world-atlas/land-50m.json
//
// world-atlas is not a dependency: `npm pack world-atlas@2.0.2` and point at it.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const COLS = 720;
const ROWS = 300;
const NORTH = 84;
const SOUTH = -66;

const src = process.argv[2];
if (!src) {
  console.error("usage: build-land.mjs <land-50m.json>");
  process.exit(1);
}
const topo = JSON.parse(readFileSync(src, "utf8"));

// Minimal topojson decode: delta-encoded, quantized arcs -> lon/lat rings.
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});
function ring(ids) {
  const out = [];
  for (const id of ids) {
    const a = id < 0 ? arcs[~id].slice().reverse() : arcs[id];
    out.push(...(out.length ? a.slice(1) : a));
  }
  return out;
}
const rings = [];
function collect(geom) {
  if (geom.type === "GeometryCollection") geom.geometries.forEach(collect);
  else if (geom.type === "Polygon") geom.arcs.forEach((r) => rings.push(ring(r)));
  else if (geom.type === "MultiPolygon") geom.arcs.forEach((p) => p.forEach((r) => rings.push(ring(r))));
}
Object.values(topo.objects).forEach(collect);

// Even-odd scanline fill per row centre; holes (lakes) fall out naturally.
const bits = new Uint8Array(Math.ceil((COLS * ROWS) / 8));
for (let r = 0; r < ROWS; r++) {
  const lat = NORTH - ((r + 0.5) / ROWS) * (NORTH - SOUTH);
  const xs = [];
  for (const pts of rings) {
    for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
      const [x1, y1] = pts[i];
      const [x2, y2] = pts[j];
      if (y1 > lat !== y2 > lat) xs.push(x1 + ((lat - y1) / (y2 - y1)) * (x2 - x1));
    }
  }
  xs.sort((a, b) => a - b);
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const c0 = Math.ceil(((xs[k] + 180) / 360) * COLS - 0.5);
    const c1 = Math.floor(((xs[k + 1] + 180) / 360) * COLS - 0.5);
    for (let c = Math.max(0, c0); c <= Math.min(COLS - 1, c1); c++) {
      const i = r * COLS + c;
      bits[i >> 3] |= 0x80 >> (i & 7);
    }
  }
}

const b64 = Buffer.from(bits).toString("base64");
const lines = b64.match(/.{1,120}/g).map((l) => `  "${l}"`).join(" +\n");
const out = `// Generated by scripts/build-land.mjs from Natural Earth land-50m (public domain).
// Do not edit by hand. ${COLS}x${ROWS} equirectangular cells, ${NORTH}N to ${-SOUTH}S, MSB first.
export const LAND_COLS = ${COLS};
export const LAND_ROWS = ${ROWS};
export const LAND_NORTH = ${NORTH};
export const LAND_SOUTH = ${SOUTH};
export const LAND_BITS_B64 =
${lines};
`;
const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(join(here, "..", "src", "land-data.ts"), out);
let land = 0;
for (const b of bits) for (let k = 0; k < 8; k++) land += (b >> k) & 1;
console.log(`wrote land-data.ts: ${COLS}x${ROWS}, ${((land / (COLS * ROWS)) * 100).toFixed(1)}% land`);
