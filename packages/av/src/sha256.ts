/**
 * SHA-256 that works everywhere CrushAV runs.
 *
 * Browsers and Node have WebCrypto, which is fast and preferred. React Native
 * (Hermes) does not, so a small pure-JS implementation is the fallback. It is
 * also incremental, so callers that stream a file can hash it chunk by chunk.
 */

