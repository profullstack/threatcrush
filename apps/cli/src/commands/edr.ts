import { accessSync, constants, existsSync } from 'node:fs';
import chalk from 'chalk';
import { loadConfig } from '../core/config.js';
import { getModuleEvents, initStateDB } from '../core/state.js';
import { PATHS } from '../daemon/paths.js';
import { generateAuditRules } from '../daemon/auditd/rules.js';
import { edrSettings } from '../daemon/workers/edr.js';

/** `threatcrush edr status|rules` — auditd process detection status and rule template. */
export async function edrCommand(action = 'status', opts: { json?: boolean; limit?: string } = {}): Promise<void> {
  const settings = edrSettings(loadConfig().edr);
  if (action === 'rules') {
    const generated = generateAuditRules(settings);
    console.log('# Generated by threatcrush edr rules. Review before loading with auditd.');
    console.log('# auditd may also write EXECVE argument records for matching syscalls;');
    console.log('# ThreatCrush reads only SYSCALL metadata and discards command arguments.');
    for (const warning of generated.warnings) console.log(`# NOTE: ${warning}`);
    if (generated.rules.length) console.log(generated.rules.join('\n'));
    return;
  }
  if (action !== 'status') {
    console.error(chalk.red(`  Unknown action "${action}". Use status or rules.`));
    process.exitCode = 1;
    return;
  }

  let readable = false;
  try {
    if (existsSync(settings.auditLogPath)) accessSync(settings.auditLogPath, constants.R_OK);
    readable = existsSync(settings.auditLogPath);
  } catch { /* reported below */ }
  let events: Array<Record<string, unknown>> = [];
  let stateNote: string | null = null;
  try {
    initStateDB(PATHS.stateDb);
    events = getModuleEvents('edr', Number(opts.limit) || 25) as unknown as Array<Record<string, unknown>>;
  } catch {
    stateNote = `the daemon state database (${PATHS.stateDb}) is not readable here`;
  }

  const report = {
    enabled: settings.enabled,
    audit_log_path: settings.auditLogPath,
    audit_log_readable: readable,
    web_service_users: settings.webServiceUsers,
    temp_exec_paths: settings.tempExecPaths,
    watch_network_syscalls: settings.watchNetworkSyscalls,
    network_baseline_seconds: settings.networkBaselineMs / 1000,
    watch_unknown_temp_cpu: settings.watchUnknownTempCpu,
    poll_interval_seconds: settings.pollMs / 1000,
    state_note: stateNote,
    events,
  };
  if (opts.json) {
    console.log(JSON.stringify(report, null, 2));
    return;
  }
  console.log(`  ${chalk.white.bold('EDR audit watch')} ${settings.enabled ? chalk.green('enabled') : chalk.gray('disabled')}`);
  console.log(`  Audit log: ${settings.auditLogPath} (${readable ? chalk.green('readable') : chalk.yellow('unavailable')})`);
  console.log(`  Service accounts: ${settings.webServiceUsers.join(', ') || 'none configured'}`);
  console.log(`  Temporary execution paths: ${settings.tempExecPaths.join(', ') || 'none configured'}`);
  console.log(`  Network syscalls: ${settings.watchNetworkSyscalls ? `enabled (learn ${settings.networkBaselineMs / 1000}s)` : 'disabled'}`);
  console.log(`  Temporary-path CPU watch: ${settings.watchUnknownTempCpu ? 'enabled' : 'disabled'}`);
  console.log(`  Recent EDR events: ${events.length}`);
  if (stateNote) console.log(chalk.gray(`  ${stateNote}`));
  if (!settings.enabled) console.log(chalk.gray('  Enable [edr] only after reviewing `threatcrush edr rules` and loading them in auditd.'));
  for (const event of events) {
    const severity = String(event.severity ?? 'info');
    const color = severity === 'critical' ? chalk.red.bold : severity === 'high' ? chalk.red : chalk.yellow;
    console.log(`    ${color(severity.padEnd(8))} ${String(event.message ?? '')}`);
  }
  console.log();
}
